# estimate cost of given input and output using gpt-4
def estimate_gpt4_cost(prompt_tokens, completion_tokens):
    input_cost = 0.03
    output_cost = 0.06
    
    return (input_cost*prompt_tokens/1000 + output_cost*completion_tokens/1000)


